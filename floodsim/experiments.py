def guide_text() -> str:
    out = ["คู่มือการทดลอง\n" + "=" * 40 + "\n"]
    for e in EXPERIMENTS:
        out.append(e["title"])
        out.append("วัตถุประสงค์: " + e["objective"])
        out.append("สิ่งที่ควรสังเกต:")
        out += ["  • " + o for o in e["observe"]]
        sw = e["sweep"]
        out.append("ชุดเปรียบเทียบ: " + ", ".join(sw["labels"]))
        out.append("คำถามชวนคิด: " + e["question"] + "\n")
    out.append("""ขั้นตอนทั่วไป
  1. เลือกการทดลอง (หรือกำหนดแม่น้ำเอง / นำเข้าไฟล์ KML)
  2. แท็บ 'เปรียบเทียบระดับน้ำ (1D)' — ดูตารางและกราฟทันที กด 'รันชุดเปรียบเทียบ' เพื่อซ้อนผลหลายสถานการณ์
  3. แท็บ 'จำลอง 2D' — เลือกระดับน้ำ กด ▶ เพื่อดูการไหลแบบเคลื่อนไหวบน GPU
  4. กด 'รัน 2D ทุกระดับน้ำ' เพื่อเปรียบเทียบพื้นที่น้ำท่วม/ความเร็วจากแบบจำลอง 2 มิติ
  5. โหมด 'คลื่นน้ำหลาก' — ดูการเดินทางและการลดทอนของยอดน้ำในแท็บ 'ไฮโดรกราฟ'

สมมติฐานของแบบจำลอง
  • 1D: การไหลสม่ำเสมอ (normal flow) ตามสมการแมนนิ่ง หน้าตัดผสมแบบแบ่งส่วน, ตัวคูณความคดเคี้ยวของ Cowan
  • 2D: สมการน้ำตื้นแบบ local inertial (LISFLOOD-FP) บนกริดสี่เหลี่ยม จำกัด Froude ≤ 1.2 เพื่อเสถียรภาพ
    (การไหลเชี่ยวมากในลำธารชันจึงถูกประมาณให้ช้าลงเล็กน้อย)
  • ภูมิประเทศสร้างจากเส้นแม่น้ำ + หน้าตัด ไม่ใช่ DEM จริง — เหมาะกับการเรียนรู้และเปรียบเทียบเชิงคุณภาพ
""")
    return "\n".join(out)
